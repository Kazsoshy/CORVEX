export function getStockStatus(stock, reorderPoint) {
  if (stock <= 0) return 'Out of Stock';
  if (stock <= reorderPoint * 0.3) return 'Critical Stock';
  if (stock <= reorderPoint) return 'Low Stock';
  return 'Sufficient';
}

